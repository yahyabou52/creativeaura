import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  ArrowUpRight, ArrowRight, ArrowLeft, ArrowDown, ArrowUp, X, Menu,
  Plus, Paperclip, Mail, MessageCircle, Check, Circle, CircleCheck,
  Pause, Play, Camera, Search,
} from "lucide-react";

// Pre-render the legacy HTML icons at build time, keeping React's server
// renderer out of the browser bundle. React pages use the components directly.
const icons = { ArrowUpRight, ArrowRight, ArrowLeft, ArrowDown, ArrowUp, X, Menu,
  Plus, Paperclip, Mail, MessageCircle, Check, Circle, CircleCheck,
  Pause, Play, Camera, Search };
const markup = Object.fromEntries(Object.entries(icons).map(([name, Component]) => [
  name, renderToStaticMarkup(React.createElement(Component, {
    size:20, strokeWidth:1.75, "aria-hidden":"true", focusable:"false", className:"ui-icon",
  })),
]));
mkdirSync(fileURLToPath(new URL("../src/generated/", import.meta.url)), { recursive:true });
writeFileSync(new URL("../src/generated/icon-markup.js", import.meta.url),
  `// Generated by scripts/generate-ui-icons.mjs. Do not edit by hand.\nexport default ${JSON.stringify(markup, null, 2)};\n`);
